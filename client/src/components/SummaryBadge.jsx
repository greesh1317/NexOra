// Small caption under a generated summary, explaining where the text came from.
function SummaryBadge({ source, reason, className = "" }) {
  let label = "Generated by AI";
  if (source !== "ai") {
    label =
      reason === "no_api_key"
        ? "Computed summary — AI is not configured (no API key)"
        : "Computed summary — AI unavailable right now (check API key / credits)";
  }
  return <p className={className}>{label}</p>;
}

export default SummaryBadge;
