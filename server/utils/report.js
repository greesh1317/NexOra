// Builds the weekly / monthly project report (as data, and as a CSV file) from tasks and daily reports.
import { summarize, completionTime, isOverdue } from "./analytics.js";
import { toCsv } from "./csv.js";

const DAY = 24 * 60 * 60 * 1000;
export const PERIODS = {
  week: { days: 7, label: "Last 7 days" },
  month: { days: 30, label: "Last 30 days" },
};
export const MAX_ROWS = 2000; // a safety limit on each table

const iso = (date) => (date ? new Date(date).toISOString().slice(0, 10) : "");
const STATUS_LABELS = { not_started: "Not started", in_progress: "In progress", completed: "Completed", blocked: "Blocked" };
const STATUS_ORDER = { blocked: 0, in_progress: 1, not_started: 2, completed: 3 };
const capital = (text) => (text ? text.charAt(0).toUpperCase() + text.slice(1) : "");

export function buildReport({ tasks, reports, projectLabel, period, generatedBy, now = new Date(), truncated = {} }) {
  const { days, label } = PERIODS[period];
  const since = new Date(now.getTime() - days * DAY);
  const inPeriod = (date) => Boolean(date) && new Date(date) >= since;

  const stats = summarize(tasks, { now, withLists: false });
  const hours = reports.reduce((sum, r) => sum + (Number(r.hours) || 0), 0);

  return {
    meta: {
      title: "NexOra project report",
      project: projectLabel,
      period,
      periodLabel: label,
      from: iso(since),
      to: iso(now),
      generatedAt: now.toISOString().slice(0, 16).replace("T", " ") + " UTC",
      generatedBy,
      truncated: { tasks: Boolean(truncated.tasks), reports: Boolean(truncated.reports) },
    },
    summary: {
      totalTasks: stats.total,
      completed: stats.byStatus.completed,
      inProgress: stats.byStatus.in_progress,
      blocked: stats.byStatus.blocked,
      notStarted: stats.byStatus.not_started,
      completionRate: stats.completionRate,
      overdue: stats.overdue,
      dueSoon: stats.dueSoon,
      completedInPeriod: tasks.filter((t) => t.status === "completed" && inPeriod(completionTime(t))).length,
      createdInPeriod: tasks.filter((t) => inPeriod(t.createdAt)).length,
      reportsInPeriod: reports.length,
      hoursInPeriod: Math.round(hours * 10) / 10,
    },
    workload: stats.byPerson,
    tasks: [...tasks]
      .sort(
        (a, b) =>
          (a.project?.title || "").localeCompare(b.project?.title || "") ||
          STATUS_ORDER[a.status] - STATUS_ORDER[b.status] ||
          (a.deadline ? new Date(a.deadline).getTime() : Infinity) - (b.deadline ? new Date(b.deadline).getTime() : Infinity)
      )
      .map((t) => ({
        project: t.project?.title || "",
        title: t.title,
        assignedTo: t.assignedUser?.name || "",
        priority: t.priority,
        status: t.status,
        deadline: iso(t.deadline),
        overdue: isOverdue(t, now),
        completedOn: t.status === "completed" ? iso(completionTime(t)) : "",
      })),
    reports: [...reports]
      .sort((a, b) => new Date(b.date) - new Date(a.date))
      .map((r) => ({
        date: iso(r.date),
        person: r.user?.name || "",
        project: r.project?.title || "",
        hours: r.hours ?? "",
        workDone: r.workDone || "",
        blockers: r.blockers || "",
      })),
  };
}

// The same report as a spreadsheet-friendly CSV file: a few sections separated by blank lines
export function reportToCsv(report) {
  const { meta, summary: s } = report;
  const rows = [
    [meta.title],
    ["Project", meta.project],
    ["Period", `${meta.periodLabel} (${meta.from} to ${meta.to})`],
    ["Generated", meta.generatedAt],
    ["Generated by", meta.generatedBy],
  ];
  if (meta.truncated.tasks) rows.push(["Note", `Only the first ${MAX_ROWS} tasks are listed`]);
  if (meta.truncated.reports) rows.push(["Note", `Only the first ${MAX_ROWS} daily reports are listed`]);

  rows.push(
    [],
    ["SUMMARY"],
    ["Total tasks", s.totalTasks],
    ["Completed", s.completed],
    ["In progress", s.inProgress],
    ["Blocked", s.blocked],
    ["Not started", s.notStarted],
    ["Completion rate (%)", s.completionRate],
    ["Overdue", s.overdue],
    ["Due in the next 7 days", s.dueSoon],
    ["Tasks completed in this period", s.completedInPeriod],
    ["Tasks created in this period", s.createdInPeriod],
    ["Daily reports in this period", s.reportsInPeriod],
    ["Hours reported in this period", s.hoursInPeriod],
    [],
    ["WORKLOAD"],
    ["Person", "Total tasks", "Open", "Completed", "Overdue", "Blocked"],
    ...report.workload.map((p) => [p.name, p.total, p.open, p.completed, p.overdue, p.blocked]),
    [],
    ["TASKS"],
    ["Project", "Task", "Assigned to", "Priority", "Status", "Deadline", "Overdue", "Completed on"],
    ...report.tasks.map((t) => [
      t.project,
      t.title,
      t.assignedTo,
      capital(t.priority),
      STATUS_LABELS[t.status] || t.status,
      t.deadline,
      t.overdue ? "Yes" : "",
      t.completedOn,
    ]),
    [],
    ["DAILY REPORTS"],
    ["Date", "Person", "Project", "Hours", "Work done", "Blockers"],
    ...report.reports.map((r) => [r.date, r.person, r.project, r.hours, r.workDone, r.blockers])
  );
  return toCsv(rows);
}

// e.g. nexora-report-website-redesign-week-2026-11-11.csv (only safe characters)
export function reportFilename(meta) {
  const slug = String(meta.project).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "report";
  return `nexora-report-${slug}-${meta.period}-${meta.to}.csv`;
}
